# Pruebas de extremo a extremo de la tienda en el diseño EDITORIAL (Playwright).
# El diseño deportivo se prueba en tools/prueba-deportivo.py. Uso: python3 tools/prueba-tienda.py [url] [carpeta_capturas]
import sys, re, os
from playwright.sync_api import sync_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/"
OUT = sys.argv[2] if len(sys.argv) > 2 else "capturas"
os.makedirs(OUT, exist_ok=True)
fallas = 0
def ok(c, m):
    global fallas
    print(("OK   " if c else "FALLA ") + m)
    if not c: fallas += 1
with sync_playwright() as p:
    b = p.chromium.launch()
    def editorial(c):  # fuerza el diseño editorial sin tocar los archivos
        def cambiar(r):
            resp = r.fetch(); r.fulfill(response=resp, body=resp.text().replace('estilo: "deportivo"', 'estilo: "editorial"'))
        c.route(re.compile(r"/js/config\.js$"), cambiar); return c
    ctx = editorial(b.new_context(viewport={"width": 1440, "height": 900}))
    pg = ctx.new_page()
    errores, dialogos = [], []
    pg.on("console", lambda m: m.type == "error" and "ERR_FAILED" not in m.text and errores.append(m.text))
    pg.on("pageerror", lambda e: errores.append(str(e)))
    pg.on("dialog", lambda d: (dialogos.append(d.message), d.dismiss()))
    pg.route(re.compile(r"fonts\.(googleapis|gstatic)\.com"), lambda r: r.abort())  # sin red externa
    pg.goto(URL); pg.wait_for_selector(".hero")
    ok(pg.locator("h1").count() == 1, "inicio: un solo h1")
    ok(pg.locator(".hoja li").count() == 15, "inicio: lista de precios con 15 productos reales")
    pg.screenshot(path=f"{OUT}/1440-inicio.png")
    ok(pg.locator(".categoria").count() == 4, "inicio: 4 categorías con enlace")
    ok(pg.locator(".v3d__item").count() == 8, "vitrina 3D: 8 prendas")
    n1 = pg.inner_text("#v3d-nombre"); pg.click("[data-v3d='1']"); pg.wait_for_timeout(2200)
    ok(pg.inner_text("#v3d-nombre") != n1, "vitrina 3D: la flecha gira a la siguiente prenda")
    caja = pg.locator("#v3d").bounding_box(); cx, cy = caja["x"] + caja["width"] / 2, caja["y"] + caja["height"] * 0.47
    pg.mouse.move(cx, cy); pg.mouse.down(); pg.mouse.move(cx - 260, cy, steps=8); pg.mouse.up(); pg.wait_for_timeout(300)
    ok("ver=producto" not in pg.url, "vitrina 3D: arrastrar no abre el producto")
    ok("Desde S/" in pg.inner_text(".hero__datos").replace("\u00a0", " "), "hero: precio desde calculado del catálogo")
    pg.click("[data-vitrina='falda-tul']"); pg.click(".muestra[data-color='lila']"); pg.wait_for_timeout(300)
    ok("falda-lila.webp" in pg.inner_html("#placa-escena"), "vitrina: muestra la foto real de la falda lila")
    ok("Falda de tul en lila" in pg.inner_text("#vitrina-nombre"), "vitrina: ficha actualizada")
    pg.screenshot(path=f"{OUT}/1440-vitrina.png", full_page=True)
    pg.click(".hero__acciones .boton"); pg.wait_for_selector(".rejilla .tarjeta")
    ok(pg.locator(".tarjeta").count() == 15, "tienda: 15 productos")
    ok("NaN" not in pg.inner_text(".rejilla") and re.search(r"S/\s25\.00", pg.inner_text(".rejilla")), "tienda: precios con formato correcto")
    pg.wait_for_timeout(600)
    rotas = pg.evaluate("[...document.images].filter(i => i.complete && i.naturalWidth === 0 && i.loading !== 'lazy').map(i => i.src)")
    ok(not rotas, "tienda: fotos cargan" + ("" if not rotas else ": " + ", ".join(rotas[:3])))
    ok(pg.locator(".tarjeta__placa > img.foto:first-child").count() == 15, "tienda: las 15 tarjetas usan foto real")
    ok(pg.locator(".tarjeta__placa--doble").count() >= 6, "tienda: tarjetas con segunda foto al pasar el mouse")
    pg.screenshot(path=f"{OUT}/1440-tienda.png")
    pg.locator("label.op--color:has(input[value='celeste'])").click(); pg.wait_for_timeout(100)
    n = pg.locator(".tarjeta").count(); ok(0 < n < 15, f"filtro color celeste: {n} productos")
    pg.locator("label.op--color:has(input[value='plateado'])").click()
    pg.select_option("select[name='precio']", "r0"); pg.wait_for_timeout(100)
    ok(pg.locator(".vacio").count() == 1, "filtros combinados sin resultado: mensaje vacío")
    pg.click("#vacio-limpiar"); pg.wait_for_timeout(100)
    ok(pg.locator(".tarjeta").count() == 15, "quitar filtros restaura los 15")
    pg.fill("#q", "talla 8 rosado"); pg.press("#q", "Enter"); pg.wait_for_timeout(200)
    n = pg.locator(".tarjeta").count(); ok(n >= 3, f"buscador 'talla 8 rosado': {n} resultados")
    pg.fill("#q", "<img src=x onerror=alert(1)>"); pg.press("#q", "Enter"); pg.wait_for_timeout(300)
    ok(not dialogos and pg.locator(".tienda img").count() == 0, "XSS en buscador se muestra como texto")
    pg.goto(URL + "?ver=producto&id=body-manga-larga"); pg.wait_for_selector(".producto")
    pg.click("button[value='carrito']")
    ok(pg.is_visible("#error-talla"), "producto: exige talla antes de añadir")
    pg.locator("label.op:has(input[value='8'])").click(); pg.click("[data-paso='1']")
    pg.click("button[value='carrito']"); pg.wait_for_timeout(200)
    ok(pg.inner_text("[data-cuenta]") == "2", "carrito: contador = 2")
    ok(pg.is_visible("#cajon") and pg.locator(".cajon__linea").count() == 1, "carrito lateral se abre al añadir")
    pg.click(".cajon__linea [data-cd='1']"); pg.wait_for_timeout(100)
    ok("3" == pg.inner_text(".cajon__linea output") and pg.inner_text("[data-cuenta]") == "3", "carrito lateral: cambia cantidad")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(200)
    ok(not pg.is_visible("#cajon"), "carrito lateral: Esc lo cierra")
    pg.click("#abrir-cajon"); pg.wait_for_timeout(200)
    ok(pg.is_visible("#cajon"), "icono del carrito abre el lateral")
    pg.click(".cajon__linea [data-cd='-1']"); pg.click("[data-cerrar-cajon].cajon__cerrar"); pg.wait_for_timeout(200)
    for _ in range(15): pg.click("[data-paso='1']")
    ok(pg.inner_text("#cant") == "10", "cantidad máxima 10")
    pg.screenshot(path=f"{OUT}/1440-producto.png")
    pg.goto(URL + "?ver=producto&id=zapatilla-plateada"); pg.wait_for_selector("#consultar")
    ok("wa.me/51912443287" in pg.get_attribute("#consultar", "href"), "precio a consultar: enlace a WhatsApp")
    ok(pg.locator("button[value='carrito']").count() == 0, "sin precio no se puede añadir al carrito")
    pg.goto(URL + "?ver=carrito"); pg.wait_for_selector(".linea")
    ok(re.search(r"50\.00", pg.inner_text("#r-sub")), "carrito: subtotal 2 × 25 = 50")
    ok("privacidad" in pg.inner_html("#form-pedido"), "pedido: enlace a política de privacidad")
    pg.fill("#f-nombre", "Ana"); pg.fill("#f-celular", "12345"); pg.fill("#f-ciudad", "Lima"); pg.click("#enviar")
    ok(pg.is_visible("#error-pedido") and pg.get_attribute("#f-celular", "aria-invalid") == "true", "pedido: valida celular")
    pg.fill("#f-celular", "987 654 321"); pg.click("#enviar"); pg.wait_for_selector("#listo:not([hidden])")
    msg = pg.inner_text("#mensaje")
    ok("2 x Body manga larga, talla 8, negro" in msg and "Celular: 987654321" in msg, "pedido: mensaje de WhatsApp correcto")
    pg.screenshot(path=f"{OUT}/1440-pedido.png")
    # carrito manipulado en localStorage
    pg.evaluate("""localStorage.setItem('da_carrito', JSON.stringify([{id:'body-manga-larga',talla:'8',color:'rosado',cant:999},{id:'falso',cant:1},{id:'zapatilla-lona',talla:'30',color:'rosado',cant:1},{id:'falda-tul',talla:'XXL',color:'rosado',cant:1}]))""")
    pg.goto(URL + "?ver=carrito"); pg.wait_for_selector(".linea")
    ok(pg.locator(".linea").count() == 1 and pg.inner_text(".linea output") == "10", "carrito manipulado: se limpia y se limita a 10")
    # uniforme de clase
    pg.evaluate("localStorage.removeItem('da_carrito')"); pg.goto(URL); pg.wait_for_selector("#u-form")
    pg.locator("#u-form button[type=submit]").click(); pg.wait_for_timeout(100)
    ok(pg.is_visible("#u-error"), "uniforme: pide talla")
    pg.locator("#u-form label.op:has(input[name=talla][value='8'])").click(); pg.wait_for_timeout(100)
    ok(re.search(r"58\.00", pg.inner_text("#u-total")), "combo: total 25 + 18 + 15 = 58")
    ok("8-10" in pg.inner_text("#u-n-2"), "combo: falda pasa a talla 8-10")
    pg.locator("#u-form label.op:has(input[name=modelo-0][value='body-manga-corta'])").click(); pg.locator("#u-form input[name=incluir-2]").uncheck(); pg.wait_for_timeout(100)
    ok(re.search(r"38\.00", pg.inner_text("#u-total")), "uniforme: manga corta sin falda = 38")
    pg.locator("#u-form label.op:has(input[name=talla][value='M'])").click(); pg.wait_for_timeout(100)
    ok("No hay en talla M" in pg.inner_text("#u-n-0"), "combo: avisa talla no disponible")
    pg.locator("#u-form label.op:has(input[name=talla][value='10'])").click(); pg.locator("#u-form input[name=incluir-2]").check()
    pg.locator("#u-form button[type=submit]").click(); pg.wait_for_timeout(300)
    ok(pg.locator(".cajon__linea").count() == 3 and re.search(r"53\.00", pg.inner_text(".cajon__total")), "uniforme: añade 3 prendas, total 53")
    ok(pg.evaluate("JSON.parse(localStorage.getItem('da_carrito')).find(i => i.id === 'falda-tul').talla") == "8-10", "uniforme: falda guardada en talla 8-10")
    pg.keyboard.press("Escape")
    # WhatsApp flotante
    ok(pg.is_visible("#wa-flotante") and "wa.me/51912443287" in pg.get_attribute("#wa-flotante", "href"), "WhatsApp flotante visible")
    pg.goto(URL + "?ver=producto&id=falda-tul"); pg.wait_for_selector(".producto")
    ok("DA-FTU" in pg.get_attribute("#wa-flotante", "href"), "WhatsApp flotante: mensaje con el producto")
    # páginas legales
    pg.goto(URL + "?ver=reclamaciones"); pg.wait_for_selector("#form-reclamo")
    ok(pg.locator(".pie__libro").count() == 1, "pie: enlace al Libro de Reclamaciones")
    pg.click("#r-enviar"); pg.wait_for_timeout(100)
    ok(pg.get_attribute("#r-nombre", "aria-invalid") == "true", "reclamo: valida nombre")
    pg.fill("#r-nombre", "Ana Prueba"); pg.fill("#r-doc", "1234567"); pg.click("#r-enviar")
    ok("8 dígitos" in pg.inner_text("#r-error"), "reclamo: valida DNI")
    pg.fill("#r-doc", "12345678"); pg.fill("#r-dom", "Av. Lima 123"); pg.fill("#r-cel", "987654321"); pg.fill("#r-correo", "ana@correo.pe")
    pg.select_option("#r-prod", "DA-FTU"); pg.fill("#r-detalle", "La falda llegó con una costura abierta."); pg.fill("#r-solicitud", "Cambio")
    pg.check("#r-acepto"); pg.click("#r-enviar"); pg.wait_for_timeout(100)
    ok("todavía no está conectado" in pg.inner_text("#r-error"), "reclamo sin base de datos: avisa y da contacto")
    pg.goto(URL + "?ver=privacidad"); pg.wait_for_selector(".legal__texto")
    ok("Ley 29733" in pg.inner_text(".legal__texto"), "política de privacidad visible")
    ok(not errores, "sin errores de consola" + ("" if not errores else ": " + "; ".join(errores[:3])))
    # teléfono
    m = editorial(b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True))
    mp = m.new_page(); mp.route(re.compile(r"fonts\.(googleapis|gstatic)\.com"), lambda r: r.abort())
    for nombre, ruta in [("inicio", ""), ("tienda", "?ver=tienda"), ("producto", "?ver=producto&id=conjunto-completo"), ("carrito", "?ver=carrito")]:
        mp.goto(URL + ruta); mp.wait_for_timeout(400)
        ancho = mp.evaluate("document.documentElement.scrollWidth")
        ok(ancho <= 390, f"390px {nombre}: sin scroll horizontal ({ancho}px)")
        mp.screenshot(path=f"{OUT}/390-{nombre}.png")
    mp.goto(URL + "?ver=producto&id=body-manga-corta"); mp.wait_for_selector(".producto")
    mp.evaluate("window.scrollTo(0, 0)"); mp.wait_for_timeout(300)
    ok(mp.is_visible("#barra-compra"), "390px producto: barra de compra visible al inicio")
    mp.click("#barra-compra button"); mp.wait_for_timeout(400)
    ok(mp.is_visible("#error-talla"), "390px barra: pide talla antes de añadir")
    mp.locator("label.op:has(input[value='10'])").click(); mp.locator(".producto__acciones").scroll_into_view_if_needed(); mp.wait_for_timeout(300)
    ok(not mp.is_visible("#barra-compra"), "390px barra: se oculta junto a los botones reales")
    mp.evaluate("window.scrollTo(0, 0)"); mp.wait_for_timeout(300)
    mp.click("#barra-compra button"); mp.wait_for_timeout(300)
    ok(mp.inner_text("[data-cuenta]") == "1", "390px barra: añade al carrito")
    mp.screenshot(path=f"{OUT}/390-barra.png")
    mp.goto(URL); mp.wait_for_timeout(300)
    box = mp.locator("#wa-flotante").bounding_box()
    ok(box and box["x"] + box["width"] <= 390 and box["width"] <= 60, "390px: WhatsApp flotante compacto")
    mp.goto(URL + "?ver=reclamaciones"); mp.wait_for_timeout(300)
    ok(mp.evaluate("document.documentElement.scrollWidth") <= 390, "390px reclamaciones: sin scroll horizontal"); mp.screenshot(path=f"{OUT}/390-reclamaciones.png")
    mp.goto(URL + "?ver=producto&id=falda-tul"); mp.locator("label.op:has(input[value='8-10'])").click(); mp.click("button[value='carrito']"); mp.wait_for_timeout(400)
    cb = mp.locator("#cajon").bounding_box()
    ok(cb and cb["width"] <= 390, "390px: carrito lateral ocupa la pantalla"); mp.screenshot(path=f"{OUT}/390-cajon.png")
    mp.keyboard.press("Escape")
    mp.goto(URL); mp.click("#boton-menu"); mp.wait_for_timeout(200)
    ok(mp.is_visible("#nav-principal"), "390px: menú desplegable abre"); mp.screenshot(path=f"{OUT}/390-menu.png")
    t = editorial(b.new_context(viewport={"width": 768, "height": 1024})).new_page(); t.route(re.compile(r"fonts\.(googleapis|gstatic)\.com"), lambda r: r.abort())
    for ruta in ["", "?ver=tienda"]:
        t.goto(URL + ruta); t.wait_for_timeout(300)
        ok(t.evaluate("document.documentElement.scrollWidth") <= 768, f"768px {ruta or 'inicio'}: sin scroll horizontal")
    t.screenshot(path=f"{OUT}/768-tienda.png")
    b.close()
print(f"\n{'TODO OK' if not fallas else str(fallas) + ' FALLAS'}")
sys.exit(1 if fallas else 0)
