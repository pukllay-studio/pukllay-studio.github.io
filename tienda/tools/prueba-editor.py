# Pruebas del editor visual (admin.html). Uso: python3 tools/prueba-editor.py [url_base] [carpeta]
import sys, re, os, json, zipfile
from playwright.sync_api import sync_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/"
OUT = sys.argv[2] if len(sys.argv) > 2 else "capturas-editor"
os.makedirs(OUT, exist_ok=True)
fallas = 0
def ok(c, m):
    global fallas
    print(("OK   " if c else "FALLA ") + m)
    if not c: fallas += 1
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={"width": 1500, "height": 950}, accept_downloads=True); pg = ctx.new_page(); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and "ERR_FAILED" not in m.text and errs.append(m.text))
    pg.route(re.compile(r"fonts\.(googleapis|gstatic)"), lambda r: r.abort())
    pg.goto(URL + "admin.html"); pg.wait_for_selector("#ed-panel h1"); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_selector("#ed-panel h1"); pg.wait_for_timeout(900)
    fr = pg.frame_locator("#ed-iframe")
    ok(pg.inner_text("#ed-modo") == "Modo local", "editor abre en modo local")
    for s in ["marca", "portada", "secciones", "productos", "categorias", "contacto", "publicar"]:
        pg.click(f"[data-seccion='{s}']"); pg.wait_for_timeout(150)
    ok(not errs, "las 7 secciones se pintan sin errores")
    pg.click("[data-seccion='marca']")
    pg.fill("[data-ruta='marca']", "Deportes Lima"); pg.wait_for_timeout(600)
    ok(fr.locator(".pie__marca, .pie-d__nombre").text_content() == "Deportes Lima" and pg.inner_text("#ed-nombre") == "Deportes Lima", "cambiar el nombre se ve en la vista previa al instante")
    pg.click("[data-paleta='Deportivo azul']"); pg.wait_for_timeout(600)
    acento = pg.frames[1].evaluate("getComputedStyle(document.documentElement).getPropertyValue('--acento').trim()")
    ok(acento == "#1f4fa8", "paleta lista cambia el color de acento de la tienda")
    pg.locator("[data-ruta='tema.tinta']").evaluate("(e)=>{e.value='#dddddd'; e.dispatchEvent(new Event('change',{bubbles:true}))}"); pg.wait_for_timeout(300)
    ok(pg.locator(".ed-alerta").count() == 1, "avisa cuando el texto no tiene buen contraste")
    pg.click("[data-paleta='Deportivo azul']"); pg.wait_for_timeout(300)
    pg.select_option("[data-ruta='tema.fuenteTitulos']", "Syne"); pg.wait_for_timeout(500)
    ok("Syne" in pg.frames[1].evaluate("getComputedStyle(document.documentElement).getPropertyValue('--display')"), "cambiar la tipografía de títulos")
    pg.set_input_files("[data-imagen='tema.logo']", "img/logo.png"); pg.wait_for_timeout(1200)
    ok(fr.locator(".barra__marca img").get_attribute("src").startswith("data:image/webp"), "subir logo se refleja en la vista previa")
    pg.screenshot(path=f"{OUT}/1-marca.png")
    pg.click("[data-seccion='portada']")
    pg.fill("[data-ruta='hero.subtitulo']", "Ropa deportiva para todo el Perú."); pg.wait_for_timeout(600)
    ok(fr.locator(".banner__texto p").inner_text() == "Ropa deportiva para todo el Perú.", "editar la frase principal")
    pg.fill("[data-ruta='hero.titular']", "Entrena fuerte"); pg.wait_for_timeout(600)
    ok(fr.locator(".banner h1").inner_text().lower() == "entrena fuerte", "editar el titular del banner")
    pg.fill("[data-ruta='anuncios']", "Envío gratis en Lima\nPaga con Yape"); pg.wait_for_timeout(600)
    ok(fr.locator("#anuncios span").count() == 2, "editar la barra de anuncios")
    pg.click("[data-seccion='secciones']")
    g = pg.locator("details.ed-grupo:has-text('Destacados con foto')"); g.locator("summary").click()
    n0 = pg.locator(".ed-orden__item").count()
    ok(n0 == 7, f"orden de portada lista 7 secciones del diseño ({n0})")
    pg.click("[data-orden='promos'][data-d='-1']"); pg.wait_for_timeout(900)
    o = ",".join(fr.locator("#app > *").evaluate_all("es => es.map(e => e.classList[0])"))
    ok(o.index("promos") < o.index("uniforme"), "subir una sección cambia el orden en la vista previa")
    g.locator("[data-ruta='promos.lista.0.titulo']").fill("Ofertas de verano"); pg.wait_for_timeout(600)
    ok("Ofertas de verano" in fr.locator(".promo").first.text_content(), "editar un destacado con foto")
    g = pg.locator("details.ed-grupo:has-text('Vitrina 3D')"); g.locator("summary").click(); g.locator("[data-ruta='secciones.vitrina3d']").uncheck(); pg.wait_for_timeout(600)
    ok(fr.locator(".v3d").count() == 0, "ocultar la vitrina 3D")
    g = pg.locator("details.ed-grupo:has-text('Preguntas frecuentes')"); g.locator("summary").click(); g.locator("[data-agregar='preguntas.lista']").click(); pg.wait_for_timeout(200)
    n = pg.locator("[data-ruta^='preguntas.lista.'][data-ruta$='.p']").count()
    pg.locator(f"[data-ruta='preguntas.lista.{n-1}.p']").fill("¿Hacen envíos a provincia?"); pg.locator(f"[data-ruta='preguntas.lista.{n-1}.r']").fill("Sí, a todo el Perú."); pg.wait_for_timeout(600)
    ok("¿Hacen envíos a provincia?" in fr.locator(".preguntas__texto").inner_text(), "agregar una pregunta frecuente")
    pg.click("[data-seccion='productos']"); pg.click("[data-accion='nuevo-producto']"); pg.wait_for_timeout(300)
    pg.fill("[data-p='nombre']", "Polo dry fit"); pg.fill("[data-p='precio']", "39.90"); pg.fill("[data-p='tallas']", "S, M, L")
    pg.locator("[data-pcolor='azul']").check(); pg.wait_for_timeout(300)
    pg.set_input_files("[data-pfotos]", "img/body-mc-amarillo.webp"); pg.wait_for_timeout(1500)
    ok(pg.locator(".ed-foto:not(.ed-foto--nueva)").count() == 1, "subir foto agrega una sola foto")
    pg.wait_for_timeout(500)
    ok(fr.locator(".producto__nombre").text_content() == "Polo dry fit" and "39.90" in fr.locator(".producto__precio").inner_text(), "producto nuevo con nombre y precio en la vista previa")
    ok(fr.locator(".producto .placa img").count() == 1, "la foto subida se ve en la vista previa")
    pg.screenshot(path=f"{OUT}/2-producto.png")
    total = pg.locator(".ed-items li").count()
    pg.click("[data-accion='duplicar-producto']"); pg.wait_for_timeout(200)
    ok(pg.locator(".ed-items li").count() == total + 1, "duplicar producto")
    pg.click("[data-accion='borrar-producto']"); ok(pg.locator(".ed-items li").count() == total + 1, "eliminar pide confirmación")
    pg.click("[data-accion='borrar-producto']"); pg.wait_for_timeout(200); ok(pg.locator(".ed-items li").count() == total, "eliminar al confirmar")
    pg.click("[data-seccion='categorias']"); pg.click("[data-accion='nueva-categoria']"); pg.wait_for_timeout(200)
    pg.fill("[data-c='nombre']", "Ropa urbana"); pg.wait_for_timeout(200)
    ok(pg.inner_text(".ed-items button[aria-current] strong") == "Ropa urbana", "crear y renombrar categoría")
    pg.fill("#nc-n", "lavanda"); pg.click(".ed-nuevo-color button"); pg.wait_for_timeout(200)
    ok(pg.locator("[data-colorcat='lavanda']").count() == 1, "agregar un color al catálogo")
    pg.click("[data-seccion='contacto']"); pg.fill("[data-ruta='whatsapp']", "51999888777"); pg.wait_for_timeout(600)
    ok("51999888777" in fr.locator("#wa-flotante").get_attribute("href"), "cambiar el WhatsApp de la tienda")
    pg.click("[data-seccion='publicar']")
    with pg.expect_download() as d: pg.click("[data-accion='descargar']")
    zpath = f"{OUT}/tienda.zip"; d.value.save_as(zpath); z = zipfile.ZipFile(zpath)
    nombres = z.namelist(); cfg = z.read("js/config.js").decode(); catl = z.read("js/catalogo.js").decode()
    ok(z.testzip() is None and "js/config.js" in nombres and "js/catalogo.js" in nombres, "descarga un .zip válido con config y catálogo")
    ok(any(n.startswith("img/subida-") for n in nombres) and "data:image" not in cfg + catl, "las fotos subidas salen como archivos en img/")
    ok('"marca": "Deportes Lima"' in cfg and "Polo dry fit" in catl and "lavanda" in catl, "los archivos tienen los cambios")
    pg.locator("details.ed-grupo:has-text('Respaldo') summary").click()
    with pg.expect_download() as d2: pg.click("[data-accion='exportar-json']")
    jpath = f"{OUT}/respaldo.json"; d2.value.save_as(jpath)
    ok(json.load(open(jpath))["config"]["marca"] == "Deportes Lima", "exportar respaldo .json")
    pg.reload(); pg.wait_for_selector("#ed-panel h1"); pg.wait_for_timeout(800)
    ok("Borrador recuperado" in pg.inner_text("#ed-estado") and pg.inner_text("#ed-nombre") == "Deportes Lima", "al recargar recupera el borrador")
    pg.click("#ed-descartar"); pg.click("#ed-descartar"); pg.wait_for_timeout(800)
    ok(pg.inner_text("#ed-nombre") == "DANZAAURA", "descartar cambios vuelve a la versión publicada")
    minimo = {"config": {"marca": "Tienda Mínima", "whatsapp": "51911111111"}, "catalogo": {"colores": {"negro": "#111111"}, "categorias": [{"id": "general", "nombre": "General", "visible": True, "orden": 1, "sub": []}],
              "productos": [{"id": "gorra", "sku": "P-GORRA", "nombre": "Gorra", "cat": "general", "sub": "", "precio": 30, "tallas": [], "colores": ["negro"], "publico": [], "fotos": [], "descripcion": "Gorra"}]}}
    open(f"{OUT}/minimo.json", "w").write(json.dumps(minimo))
    pg.click("[data-seccion='publicar']"); pg.locator("details.ed-grupo:has-text('Respaldo') summary").click()
    pg.set_input_files("[data-importar]", f"{OUT}/minimo.json"); pg.wait_for_timeout(1200)
    ok(pg.inner_text("#ed-nombre") == "Tienda Mínima" and fr.locator(".pie__marca, .pie-d__nombre").text_content() == "Tienda Mínima", "importar respaldo de otra tienda (con un solo producto)")
    ok(fr.locator(".banner, .hero").count() == 1, "una tienda con un solo producto se muestra sin romperse")
    pg.click("[data-seccion='marca']"); pg.select_option("[data-ruta='tema.estilo']", "editorial"); pg.wait_for_timeout(800)
    ok(fr.locator(".hero").count() == 1 and fr.locator(".banner").count() == 0, "cambiar al diseño editorial desde el editor")
    pg.select_option("[data-ruta='tema.estilo']", "deportivo"); pg.wait_for_timeout(800)
    ok(fr.locator(".banner").count() == 1, "volver al diseño deportivo")
    ok(not errs, "sin errores de consola" + ("" if not errs else ": " + " | ".join(errs[:3])))
    m = b.new_page(viewport={"width": 390, "height": 844}); m.route(re.compile(r"fonts\.(googleapis|gstatic)"), lambda r: r.abort())
    m.goto(URL + "admin.html"); m.wait_for_selector("#ed-panel h1"); m.wait_for_timeout(400)
    ok(m.evaluate("document.documentElement.scrollWidth") <= 390, "editor en celular sin scroll horizontal"); m.screenshot(path=f"{OUT}/3-celular.png")
    b.close()
print(f"\n{'TODO OK' if not fallas else str(fallas) + ' FALLAS'}")
sys.exit(1 if fallas else 0)
